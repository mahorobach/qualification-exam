let changed = 0;
const errors = [];
const normalize = (value) => value.normalize("NFKC").replace(/\s|[、。，．]/g, "");

for (const year of [2024, 2025]) {
  const yearly = questions.filter((question) => question.year === year);
  if (yearly.length !== 80) throw new Error(`${year}: expected 80 questions`);

  for (const [number, choice] of Object.entries(replacements[year])) {
    const question = yearly[Number(number) - 1];
    if (!question || question.choices.length !== 5) {
      errors.push(`${year}-${number}: expected a five-choice question`);
      continue;
    }
    if (question.choices.slice(0, 4).map(normalize).includes(normalize(choice))) {
      errors.push(`${year}-${number}: replacement duplicates an existing choice`);
      continue;
    }
    question.choices[4] = choice;
    changed += 1;
  }
}

if (errors.length) throw new Error(errors.join(", "));

fs.writeFileSync(dataPath, `${JSON.stringify(questions, null, 2)}\n`);
fs.writeFileSync(
  bundlePath,
  `// Generated from questions.json. Enables the quiz to run from file:// URLs.\nwindow.KIKAI_QUESTIONS = ${JSON.stringify(questions)};\n`
);

console.log(`Replaced ${changed} fifth choices.`);
